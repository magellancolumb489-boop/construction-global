create table if not exists public.account_deletion_requests (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null unique references auth.users(id) on delete cascade,
  requested_at   timestamptz not null default now(),
  scheduled_for  timestamptz not null,
  reason         text,
  status         text not null default 'pending',
  constraint account_deletion_requests_status_enum
    check (status in ('pending','processing','completed','cancelled'))
);

create index if not exists account_deletion_requests_status_idx
  on public.account_deletion_requests (status, scheduled_for);

alter table public.account_deletion_requests enable row level security;
do $$ begin execute 'alter table public.account_deletion_requests force row level security'; exception when others then null; end $$;

drop policy if exists "del_req_select_self"  on public.account_deletion_requests;
drop policy if exists "del_req_insert_self"  on public.account_deletion_requests;
drop policy if exists "del_req_update_self"  on public.account_deletion_requests;
drop policy if exists "del_req_delete_admin" on public.account_deletion_requests;

create policy "del_req_select_self"
on public.account_deletion_requests for select
to authenticated
using (auth.uid() = user_id or public.is_admin());

create policy "del_req_insert_self"
on public.account_deletion_requests for insert
to authenticated
with check (auth.uid() = user_id and status = 'pending');

-- Self can only transition pending → cancelled. Admin handles processing/completed.
create policy "del_req_update_self"
on public.account_deletion_requests for update
to authenticated
using (auth.uid() = user_id or public.is_admin())
with check (
  public.is_admin()
  or (auth.uid() = user_id and status in ('pending','cancelled'))
);

create policy "del_req_delete_admin"
on public.account_deletion_requests for delete
to authenticated
using (public.is_admin());

