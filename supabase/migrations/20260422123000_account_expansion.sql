using (auth.uid() = reviewer_id or public.is_admin());

-- Lock reviewer/target ids on update.
create or replace function public.tg_reviews_lock_ids()
returns trigger
language plpgsql
as $$
begin
  if new.reviewer_id is distinct from old.reviewer_id then
    raise exception 'reviewer_id is immutable' using errcode = '42501';
  end if;
  if new.target_user_id is distinct from old.target_user_id then
    raise exception 'target_user_id is immutable' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists reviews_lock_ids on public.reviews;
create trigger reviews_lock_ids
  before update on public.reviews
  for each row execute function public.tg_reviews_lock_ids();

