  id, display_name, avatar_path, bio, website_url, company_name,
  entity_type, seller_activated_at
) on public.profiles to anon, authenticated;

-- ============================================================================
-- 2) user_addresses: one user → many addresses. Flags mark defaults; partial
--    unique indexes enforce at most one default-billing and one default-shipping.
-- ============================================================================

create table if not exists public.user_addresses (
  id                     bigint generated by default as identity primary key,
  user_id                uuid not null references auth.users(id) on delete cascade,
  label                  text,
  recipient              text,
  line1                  text not null,
  line2                  text,
  city                   text not null,
  county                 text,
  postal_code            text,
  country                text not null default 'RO',
  phone                  text,
  notes                  text,
  is_default_billing     boolean not null default false,
  is_default_shipping    boolean not null default false,
  pickup_lat             numeric,
  pickup_lng             numeric,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  constraint user_addresses_line1_nonempty   check (char_length(line1) between 1 and 200),
  constraint user_addresses_city_nonempty    check (char_length(city)  between 1 and 120),
  constraint user_addresses_lat_range        check (pickup_lat is null or (pickup_lat between -90  and 90)),
  constraint user_addresses_lng_range        check (pickup_lng is null or (pickup_lng between -180 and 180))
);

create index if not exists user_addresses_user_id_idx
  on public.user_addresses (user_id);

create unique index if not exists user_addresses_one_default_billing_idx
  on public.user_addresses (user_id)
  where is_default_billing;

create unique index if not exists user_addresses_one_default_shipping_idx
  on public.user_addresses (user_id)
  where is_default_shipping;

drop trigger if exists touch_updated_at on public.user_addresses;
create trigger touch_updated_at
  before update on public.user_addresses
  for each row execute function public.tg_touch_updated_at();

alter table public.user_addresses enable row level security;
do $$ begin execute 'alter table public.user_addresses force row level security'; exception when others then null; end $$;

drop policy if exists "user_addresses_select_self" on public.user_addresses;
drop policy if exists "user_addresses_insert_self" on public.user_addresses;
drop policy if exists "user_addresses_update_self" on public.user_addresses;
drop policy if exists "user_addresses_delete_self" on public.user_addresses;

create policy "user_addresses_select_self"
on public.user_addresses for select
to authenticated
using (auth.uid() = user_id or public.is_admin());

create policy "user_addresses_insert_self"
on public.user_addresses for insert
to authenticated
with check (auth.uid() = user_id);

create policy "user_addresses_update_self"
on public.user_addresses for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "user_addresses_delete_self"
on public.user_addresses for delete
to authenticated
using (auth.uid() = user_id);

-- user_id lock: belt-and-suspenders so an update cannot reassign rows.
create or replace function public.tg_user_addresses_lock_user_id()
returns trigger
language plpgsql
as $$
begin
  if new.user_id is distinct from old.user_id then
    raise exception 'user_id is immutable' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists user_addresses_lock_user_id on public.user_addresses;
create trigger user_addresses_lock_user_id
  before update on public.user_addresses
  for each row execute function public.tg_user_addresses_lock_user_id();

