-- Account overhaul: profile expansion + buyer/seller feature tables.
-- Additive-only. Uses the Phase 1 baseline (public.is_admin, tg_touch_updated_at).
-- Safe to re-run: every CREATE is idempotent and every policy is DROP-IF-EXISTS
-- before being re-created deterministically.

begin;

-- ============================================================================
-- 1) profiles: extend with marketplace-grade columns. All are nullable/default
--    so the column adds are non-breaking for existing rows. JSONB payloads
--    keep this iteration light; they can be normalized into relational tables
--    in a later phase without touching UI wiring.
-- ============================================================================

alter table public.profiles
  add column if not exists bio               text,
  add column if not exists website_url       text,
  add column if not exists entity_type       text,
  add column if not exists company_name      text,
  add column if not exists tax_id            text,
  add column if not exists reg_com           text,
  add column if not exists vat_id            text,
  add column if not exists fiscal_address    jsonb,
  add column if not exists seller_activated_at timestamptz,
  add column if not exists preferences       jsonb not null default '{}'::jsonb,
  add column if not exists seller_policies   jsonb not null default '{}'::jsonb,
  add column if not exists supplier_settings jsonb not null default '{}'::jsonb;

do $$
begin
  alter table public.profiles
    drop constraint if exists profiles_entity_type_check;
exception when others then null;
end $$;

alter table public.profiles
  add constraint profiles_entity_type_check
  check (entity_type is null or entity_type in ('PF','PFA','SRL','SA','II','IF'));

-- Open SELECT on the new public-safe columns so the public_profiles view
-- plus joins (e.g. a seller detail page) can read them without leaking
