-- ============================================================================
-- 5) reviews: buyer → seller, optionally bound to an order/listing.
--    Anyone can SELECT (public reputation); only reviewer can modify own row;
--    target_user_id cannot touch rows targeting them.
-- ============================================================================

create table if not exists public.reviews (
  id               bigint generated by default as identity primary key,
  reviewer_id      uuid not null references auth.users(id) on delete cascade,
  target_user_id   uuid not null references auth.users(id) on delete cascade,
  order_id         bigint,
  listing_id       bigint references public.marketplace_listings(id) on delete set null,
  rating           integer not null,
  title            text,
  body             text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint reviews_rating_range        check (rating between 1 and 5),
  constraint reviews_body_len            check (body is null or char_length(body) between 1 and 4000),
  constraint reviews_title_len           check (title is null or char_length(title) between 1 and 200),
  constraint reviews_reviewer_ne_target  check (reviewer_id <> target_user_id)
);

-- One review per reviewer per listing subject. Order-based uniqueness once orders land.
create unique index if not exists reviews_reviewer_listing_uniq
  on public.reviews (reviewer_id, listing_id)
  where listing_id is not null;

create index if not exists reviews_target_user_id_idx  on public.reviews (target_user_id);
create index if not exists reviews_reviewer_id_idx     on public.reviews (reviewer_id);
create index if not exists reviews_listing_id_idx      on public.reviews (listing_id);
create index if not exists reviews_created_at_idx      on public.reviews (created_at desc);

drop trigger if exists touch_updated_at on public.reviews;
create trigger touch_updated_at
  before update on public.reviews
