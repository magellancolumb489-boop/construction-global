create table if not exists public.messages (
  id            bigint generated by default as identity primary key,
  thread_id     bigint not null references public.message_threads(id) on delete cascade,
  sender_id     uuid not null references auth.users(id) on delete cascade,
  body          text not null,
  attachments   jsonb not null default '[]'::jsonb,
  read_at       timestamptz,
  created_at    timestamptz not null default now(),
  constraint messages_body_len check (char_length(body) between 1 and 4000)
);

create index if not exists messages_thread_id_idx  on public.messages (thread_id, created_at);
create index if not exists messages_sender_id_idx  on public.messages (sender_id);

alter table public.messages enable row level security;
do $$ begin execute 'alter table public.messages force row level security'; exception when others then null; end $$;

drop policy if exists "messages_select_member"  on public.messages;
drop policy if exists "messages_insert_member"  on public.messages;
drop policy if exists "messages_update_member"  on public.messages;
drop policy if exists "messages_no_delete"      on public.messages;

create policy "messages_select_member"
on public.messages for select
to authenticated
using (
  exists (
    select 1 from public.message_threads mt
    where mt.id = messages.thread_id
      and (auth.uid() in (mt.buyer_id, mt.seller_id) or public.is_admin())
  )
);

create policy "messages_insert_member"
on public.messages for insert
to authenticated
with check (
  auth.uid() = sender_id
  and exists (
    select 1 from public.message_threads mt
    where mt.id = thread_id
      and auth.uid() in (mt.buyer_id, mt.seller_id)
  )
);

-- Only the recipient can mark read_at; sender cannot modify the body.
create policy "messages_update_member"
on public.messages for update
to authenticated
using (
  exists (
    select 1 from public.message_threads mt
    where mt.id = messages.thread_id
      and auth.uid() in (mt.buyer_id, mt.seller_id)
  )
)
with check (
  exists (
    select 1 from public.message_threads mt
    where mt.id = messages.thread_id
      and auth.uid() in (mt.buyer_id, mt.seller_id)
  )
);

create policy "messages_no_delete"
on public.messages for delete
to authenticated
using (public.is_admin());

-- Freeze body/sender/thread against tampering via PostgREST.
create or replace function public.tg_messages_lock_body()
returns trigger
language plpgsql
as $$
begin
  if new.thread_id is distinct from old.thread_id then
    raise exception 'thread_id is immutable' using errcode = '42501';
  end if;
  if new.sender_id is distinct from old.sender_id then
    raise exception 'sender_id is immutable' using errcode = '42501';
  end if;
  if new.body is distinct from old.body then
    raise exception 'body is immutable' using errcode = '42501';
  end if;
  if new.attachments is distinct from old.attachments then
    raise exception 'attachments are immutable' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists messages_lock_body on public.messages;
create trigger messages_lock_body
  before update on public.messages
  for each row execute function public.tg_messages_lock_body();

-- Bump thread.last_message_at on every INSERT into messages.
create or replace function public.tg_messages_touch_thread()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  update public.message_threads
     set last_message_at = new.created_at
   where id = new.thread_id;
  return new;
end;
$$;

drop trigger if exists messages_touch_thread on public.messages;
create trigger messages_touch_thread
  after insert on public.messages
  for each row execute function public.tg_messages_touch_thread();

